// ========== 扁平区划数据构建（供 area-manage 模块的表格/树使用） ==========

function buildFlatAreaData() {
  var data = [];
  data.push({ id: 1, code: '440305', name: '南山区', level: 1, parentId: 0, fullPath: '南山区', sortOrder: 1, status: 'ENABLED', isSystem: true, expanded: true });

  var codeIdx = 1;
  STREETS.forEach(function(st, si) {
    var sId = si + 2;
    var sCode = '440305' + String(codeIdx).padStart(3, '0');
    data.push({ id: sId, code: sCode, name: st.name, level: 2, parentId: 1, fullPath: '南山区/' + st.name, sortOrder: si + 1, status: 'ENABLED', isSystem: false, expanded: false });

    st.communities.forEach(function(comm, ci) {
      var cId = sId * 100 + ci + 1;
      var cCode = sCode + String(ci + 1).padStart(3, '0');
      data.push({ id: cId, code: cCode, name: comm.name, level: 3, parentId: sId, fullPath: '南山区/' + st.name + '/' + comm.name, sortOrder: ci + 1, status: 'ENABLED', isSystem: false, expanded: false });

      comm.grids.forEach(function(gridName, gi) {
        var gId = cId * 100 + gi + 1;
        var gCode = cCode + String(gi + 1).padStart(3, '0');
        data.push({ id: gId, code: gCode, name: gridName, level: 4, parentId: cId, fullPath: '南山区/' + st.name + '/' + comm.name + '/' + gridName, sortOrder: gi + 1, status: 'ENABLED', isSystem: false });
      });
    });
    codeIdx++;
  });
  return data;
}

// ========== 层级区划树构建（供 ent-manage 模块的树渲染器使用） ==========

function buildDistrictTree() {
  var root = { id: 1, name: '南山区', children: [] };
  STREETS.forEach(function(st, si) {
    var sId = si + 2;
    var streetNode = { id: sId, name: st.name, children: [] };
    st.communities.forEach(function(comm, ci) {
      var cId = sId * 100 + ci + 1;
      var commNode = { id: cId, name: comm.name, children: [] };
      comm.grids.forEach(function(gridName, gi) {
        var gId = cId * 100 + gi + 1;
        commNode.children.push({ id: gId, name: gridName });
      });
      streetNode.children.push(commNode);
    });
    root.children.push(streetNode);
  });
  return [root];
}

// ========== 重点场所区划树（区→街道→社区，无网格） ==========

/**
 * 构建重点场所模块使用的区划树结构
 * 返回格式：{ code, name, streets: [{ code, name, communities: [{ name, grids: [string] }] }] }
 * 数据源自 STREETS 数组，确保与区域管理模块一致
 */
function buildKeyPlaceRegionTree() {
  var root = { code: REGION_ROOT.code, name: REGION_ROOT.name, streets: [] };
  var codeIdx = 0;
  STREETS.forEach(function(st) {
    codeIdx++;
    var streetCode = REGION_ROOT.code + String(codeIdx).padStart(3, '0');
    var communities = st.communities.map(function(c) { return { name: c.name, grids: c.grids.slice() }; });
    root.streets.push({ code: streetCode, name: st.name, communities: communities });
  });
  return root;
}

