// 获取节点全路径
function getDistrictFullPath(nodeId) {
  var flat = buildFlatAreaData();
  var node = flat.find(function(n) { return n.id === nodeId; });
  return node ? node.fullPath : '';
}

// Build a street name -> street ID mapping
function getStreetIdMap() {
  var map = {};
  STREETS.forEach(function(st, si) {
    map[st.name] = si + 2;
  });
  return map;
}

// Build a community name -> full path mapping (within a specific street)
// Returns: { "南山街道/南山社区": "南山区/南山街道/南山社区", ... }
function getCommunityPathMap() {
  var map = {};
  STREETS.forEach(function(st) {
    st.communities.forEach(function(comm) {
      var key = st.name + '/' + comm.name;
      map[key] = '南山区/' + key;
    });
  });
  return map;
}
